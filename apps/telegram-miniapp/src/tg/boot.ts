import type { TgWebApp } from "./types";

export type BootMode =
  | { kind: "telegram"; initData: string; startParam: string | null; languageCode: string | null }
  | { kind: "dev"; initData: string; startParam: string | null; languageCode: string | null }
  | { kind: "outside"; languageCode: string | null };

export interface BootInput {
  wa: TgWebApp | null;
  isDev: boolean;
  devInitData: string;
  search: string;
  navigatorLanguage?: string | null;
}

function userLanguageFromInitData(initData: string): string | null {
  try {
    const raw = new URLSearchParams(initData).get("user");
    if (!raw) return null;
    const user = JSON.parse(raw) as { language_code?: unknown };
    return typeof user.language_code === "string" ? user.language_code : null;
  } catch {
    return null;
  }
}

function startParamFromSearch(search: string): string | null {
  try {
    const p = new URLSearchParams(search);
    return p.get("startapp") ?? p.get("tgWebAppStartParam");
  } catch {
    return null;
  }
}

/**
 * Decides how the app starts:
 *  - inside Telegram: signed initData from WebApp (validated on the BFF);
 *  - dev build in a browser: VITE_DEV_INIT_DATA (generated by the BFF dev script);
 *  - production outside Telegram: «Откройте TilHero в Telegram».
 */
export function resolveBoot(input: BootInput): BootMode {
  const { wa } = input;
  if (wa && typeof wa.initData === "string" && wa.initData.length > 0) {
    return {
      kind: "telegram",
      initData: wa.initData,
      startParam: wa.initDataUnsafe?.start_param ?? startParamFromSearch(input.search),
      languageCode: wa.initDataUnsafe?.user?.language_code ?? null,
    };
  }
  if (input.isDev && input.devInitData) {
    return {
      kind: "dev",
      initData: input.devInitData,
      startParam: startParamFromSearch(input.search),
      languageCode: userLanguageFromInitData(input.devInitData),
    };
  }
  return { kind: "outside", languageCode: input.navigatorLanguage ?? null };
}
